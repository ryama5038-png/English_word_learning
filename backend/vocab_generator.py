def _infer_pos_meanings(word_spell: str, hint_pos: str, jp: str):
    noun, verb, adj, adv = None, None, None, None
    if hint_pos == "noun":
        noun = jp
    elif hint_pos == "verb":
        verb = jp
    elif hint_pos == "adj":
        adj = jp
    elif hint_pos == "adv":
        adv = jp
    return noun, verb, adj, adv


def generate_all_words():
    """
    重複のない 2,000語以上の単語辞書リストを返す。
    各要素は {"word_spell", "level", "noun_meaning", "verb_meaning", "adj_meaning", "adv_meaning"}
    """
    words_map = {}

    def add_entry(spell: str, level: str, noun=None, verb=None, adj=None, adv=None):
        clean_spell = spell.strip().replace("_adj", "").replace("_noun", "").replace("_verb", "").replace("_pos", "").replace("_change", "").replace("_slope", "").replace("_level", "").replace("_rule", "").replace("_firm", "").replace("_pair", "").replace("_law", "")
        if "_" in clean_spell:
            clean_spell = clean_spell.replace("_", " ")
        # 先頭大文字の正規化（固有名詞以外は小文字に統一）
        clean_spell = clean_spell.lower()
        if not clean_spell:
            return
        if clean_spell in words_map:
            existing = words_map[clean_spell]
            if noun and not existing["noun_meaning"]:
                existing["noun_meaning"] = noun
            if verb and not existing["verb_meaning"]:
                existing["verb_meaning"] = verb
            if adj and not existing["adj_meaning"]:
                existing["adj_meaning"] = adj
            if adv and not existing["adv_meaning"]:
                existing["adv_meaning"] = adv
        else:
            words_map[clean_spell] = {
                "word_spell": clean_spell,
                "level": level,
                "noun_meaning": noun,
                "verb_meaning": verb,
                "adj_meaning": adj,
                "adv_meaning": adv,
            }

    # 1. 多義語・複数品詞単語
    for spell, level, n, v, j, d in MULTI_POS_WORDS:
        add_entry(spell, level, n, v, j, d)

    # 2. 動詞派生4語ファミリー
    for v_w, n_w, j_w, d_w, level, jp_v, jp_n, jp_j, jp_d in VERB_FAMILIES:
        add_entry(v_w, level, verb=jp_v)
        add_entry(n_w, level, noun=jp_n)
        add_entry(j_w, level, adj=jp_j)
        # 4番目は -ly 副詞または派生語
        if d_w.endswith("ly"):
            add_entry(d_w, level, adv=jp_d)
        elif d_w.startswith(("re", "un", "in", "dis", "mis", "pre", "fore", "under")):
            if "する" in jp_d:
                add_entry(d_w, level, verb=jp_d)
            else:
                add_entry(d_w, level, adj=jp_d)
        else:
            add_entry(d_w, level, noun=jp_d)

    # 3. 形容詞・名詞・反意語4語ファミリー
    for j_w, d_w, n_w, ant_w, level, jp_j, jp_d, jp_n, jp_ant in ADJ_NOUN_FAMILIES:
        add_entry(j_w, level, adj=jp_j)
        if d_w.endswith("ly"):
            add_entry(d_w, level, adv=jp_d)
        else:
            add_entry(d_w, level, noun=jp_d)
        add_entry(n_w, level, noun=jp_n)
        add_entry(ant_w, level, adj=jp_ant)

    # 4. 大学入試必須ペア
    from vocab_extra import EXTRA_EXAM_PAIRS
    for w1, p1, jp1, w2, p2, jp2, level in (EXAM_PAIRS + EXTRA_EXAM_PAIRS):
        n1, v1, j1, d1 = _infer_pos_meanings(w1, p1, jp1)
        add_entry(w1, level, n1, v1, j1, d1)
        n2, v2, j2, d2 = _infer_pos_meanings(w2, p2, jp2)
        add_entry(w2, level, n2, v2, j2, d2)

    return list(words_map.values())
